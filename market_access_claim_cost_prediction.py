from statsmodels.tsa.arima.model import ARIMA
import pandas as pd

df["MonthStart"] = pd.to_datetime(df["MonthStart"])

diseases = df["Disease"].unique()

all_forecasts = []

for disease_name in diseases:

    temp = df[df["Disease"] == disease_name].copy()
    temp = temp.sort_values("MonthStart")

    temp = temp[["MonthStart", "PatientCount"]].dropna()
    temp.set_index("MonthStart", inplace=True)

    ts = temp["PatientCount"]

    ts_smooth = ts.rolling(window=3).mean().dropna()

    if len(ts_smooth) < 6:
        continue

    model = ARIMA(ts_smooth, order=(1,1,1))
    model_fit = model.fit()

    forecast = model_fit.forecast(steps=6)

    future_dates = pd.date_range(
        start=ts_smooth.index[-1] + pd.DateOffset(months=1),
        periods=6,
        freq="MS"
    )

    out = pd.DataFrame({
        "MonthStart": future_dates,
        "ForecastPatientCount": forecast.values
    })

    out["Disease"] = disease_name
    out["EstimatedRevenue"] = out["ForecastPatientCount"] * 500 * 0.3

    all_forecasts.append(out)

final_forecast = pd.concat(all_forecasts, ignore_index=True)

final_forecast.to_csv("top3_disease_arima_forecast.csv", index=False)

